BEGIN;

CREATE TABLE IF NOT EXISTS product_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(250) NOT NULL,
    category_name VARCHAR(120) NOT NULL DEFAULT 'Otros',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE product_presentations ADD COLUMN IF NOT EXISTS group_id BIGINT;
CREATE INDEX IF NOT EXISTS product_presentations_group_idx ON product_presentations(group_id);

INSERT INTO product_groups(name, category_name)
SELECT DISTINCT p.name, COALESCE(c.name, 'Otros')
FROM products p
LEFT JOIN categories c ON c.id = p.category_id
WHERE p.active
  AND NOT EXISTS (
    SELECT 1 FROM product_groups g
    WHERE lower(g.name) = lower(p.name)
      AND lower(g.category_name) = lower(COALESCE(c.name, 'Otros'))
  );

UPDATE product_presentations pp
SET group_id = g.id
FROM products p
LEFT JOIN categories c ON c.id = p.category_id
JOIN product_groups g ON lower(g.name) = lower(p.name)
  AND lower(g.category_name) = lower(COALESCE(c.name, 'Otros'))
WHERE pp.product_id = p.id AND pp.group_id IS NULL;

COMMIT;
